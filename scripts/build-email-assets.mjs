/**
 * Builds the image the transactional emails embed (lib/email/assets.ts).
 *
 * Emails can't use SVG, and externally hosted images are blocked by default in
 * Outlook and break until the site is deployed, so the logo ships inside each
 * email as an inline (CID) attachment. This renders it once and writes it as
 * base64 into a module, which keeps the send path free of filesystem reads
 * (those are fragile in serverless bundles).
 *
 * Re-run after changing the logo:  node scripts/build-email-assets.mjs
 */
import { readFile, writeFile } from "node:fs/promises";

import sharp from "sharp";

const root = new URL("../", import.meta.url);

// The clover mark. The SVG wraps raster layers, so render it big, trim the
// empty margin, then shrink to 2x of its display size.
const logo = await sharp(await readFile(new URL("public/clover-logo.svg", root)), { density: 30 })
  .trim()
  .resize({ height: 120 })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer();

const output = `/**
 * Generated by scripts/build-email-assets.mjs — don't edit by hand.
 * The logo, embedded in the transactional emails as an inline (CID) attachment.
 */
export const emailAssets = ${JSON.stringify(
  { logo: { contentType: "image/png", base64: logo.toString("base64") } },
  null,
  2,
)} as const;
`;

await writeFile(new URL("lib/email/assets.ts", root), output);

console.log(`logo ${(logo.length / 1024).toFixed(1)} KB`);
