/**
 * Builds the images the transactional emails embed (lib/email/assets.ts).
 *
 * Emails can't use SVG, and externally hosted images are blocked by default in
 * Outlook and break until the site is deployed, so the images ship inside each
 * email as inline (CID) attachments. This renders them once and writes them as
 * base64 into a module, which keeps the send path free of filesystem reads
 * (those are fragile in serverless bundles).
 *
 * Re-run after changing the logo or hero photo:  node scripts/build-email-assets.mjs
 */
import { readFile, writeFile } from "node:fs/promises";

import sharp from "sharp";

const root = new URL("../", import.meta.url);
const read = (path) => readFile(new URL(path, root));

// The clover mark. The SVG wraps raster layers, so render it big, trim the
// empty margin, then shrink to 2x of its 44px display size.
const logo = await sharp(await read("public/clover-logo.svg"), { density: 30 })
  .trim()
  .resize({ height: 120 })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer();

// Ink diffusing in water: black and white already, and chemistry at a glance.
// Displayed 600x260, rendered 2x for retina screens.
const hero = await sharp(await read("public/CTA/CTA3.jpg"))
  .resize({ width: 1200, height: 520, fit: "cover", position: "attention" })
  .grayscale()
  .linear(1.12, -8)
  .jpeg({ quality: 72, mozjpeg: true })
  .toBuffer();

// Hazard-tape stripes, displayed 600x12.
const stripeSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="24">
  <defs>
    <pattern id="s" width="24" height="24" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">
      <rect width="12" height="24" fill="#0a0a0a"/>
      <rect x="12" width="12" height="24" fill="#ffffff"/>
    </pattern>
  </defs>
  <rect width="1200" height="24" fill="url(#s)"/>
</svg>`;
const stripes = await sharp(Buffer.from(stripeSvg)).png({ compressionLevel: 9, palette: true }).toBuffer();

const asset = (buffer, contentType) => ({ contentType, base64: buffer.toString("base64") });

const output = `/**
 * Generated by scripts/build-email-assets.mjs — don't edit by hand.
 * Images embedded in the transactional emails as inline (CID) attachments.
 */
export const emailAssets = ${JSON.stringify(
  {
    logo: asset(logo, "image/png"),
    hero: asset(hero, "image/jpeg"),
    stripes: asset(stripes, "image/png"),
  },
  null,
  2,
)} as const;
`;

await writeFile(new URL("lib/email/assets.ts", root), output);

console.log(
  `logo ${(logo.length / 1024).toFixed(1)} KB, hero ${(hero.length / 1024).toFixed(1)} KB, stripes ${(stripes.length / 1024).toFixed(1)} KB`,
);
